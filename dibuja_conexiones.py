def font(size):
    return ImageFont.truetype('C:/Windows/Fonts/arial.ttf', size)
def text(x, y, s, size=27, color='#15283d'):
    d.text((x, y), s, font=font(size), fill=color)
def box(rect, color='#ffffff'):
    d.rounded_rectangle(rect, radius=18, fill=color, outline='#51677e', width=3)
def wire(points, color):
    d.line(points, fill=color, width=8)
    for x, y in (points[0], points[-1]):
        d.ellipse((x-7,y-7,x+7,y+7), fill=color)

